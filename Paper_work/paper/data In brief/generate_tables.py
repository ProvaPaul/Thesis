"""
Generates LaTeX fragments (numbers.tex macro file + sample_table.tex) from
stats.json / the raw dataset, so every number and example row quoted in
main.tex is sourced programmatically rather than hand-typed.
Run analyze_dataset.py first.
"""
import json
import os

import pandas as pd

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATASET_PATH = os.path.join(BASE_DIR, "..", "wsd_dataset.xlsx")

with open(os.path.join(BASE_DIR, "stats.json"), encoding="utf-8") as f:
    s = json.load(f)


def fnum(x, nd=2):
    return f"{x:.{nd}f}"


macros = f"""% AUTO-GENERATED by generate_tables.py -- do not hand-edit.
% Source of truth: stats.json, computed by analyze_dataset.py from wsd_dataset.xlsx
\\newcommand{{\\NRows}}{{{s['n_rows']}}}
\\newcommand{{\\NCols}}{{{s['n_cols']}}}
\\newcommand{{\\NWords}}{{{s['unique_target_word_strings']}}}
\\newcommand{{\\NWordEntries}}{{{s['unique_word_id']}}}
\\newcommand{{\\NMultiEntryWords}}{{{s['target_words_with_multiple_word_ids']}}}
\\newcommand{{\\NSenseGlossStrings}}{{{s['unique_sense_gloss_strings']}}}
\\newcommand{{\\NWordSensePairs}}{{{s['unique_target_word_sense_gloss_pairs']}}}
\\newcommand{{\\NWordIdSensePairs}}{{{s['unique_word_id_sense_id_pairs']}}}
\\newcommand{{\\SensesPerEntryMin}}{{{s['senses_per_word_id']['min']}}}
\\newcommand{{\\SensesPerEntryMax}}{{{s['senses_per_word_id']['max']}}}
\\newcommand{{\\SensesPerEntryMean}}{{{fnum(s['senses_per_word_id']['mean'])}}}
\\newcommand{{\\ExPerWordMin}}{{{s['examples_per_target_word']['min']}}}
\\newcommand{{\\ExPerWordMax}}{{{s['examples_per_target_word']['max']}}}
\\newcommand{{\\ExPerWordMean}}{{{fnum(s['examples_per_target_word']['mean'])}}}
\\newcommand{{\\ExPerClassMin}}{{{s['examples_per_word_sense_class']['min']}}}
\\newcommand{{\\ExPerClassMax}}{{{s['examples_per_word_sense_class']['max']}}}
\\newcommand{{\\ExPerClassMean}}{{{fnum(s['examples_per_word_sense_class']['mean'])}}}
\\newcommand{{\\RowsTargetNotInText}}{{{s['rows_target_word_not_in_text']}}}
\\newcommand{{\\MissingCells}}{{{s['missing_values_total']}}}
\\newcommand{{\\DupFullExtra}}{{{s['duplicate_full_rows_extra']}}}
\\newcommand{{\\DupTextExtra}}{{{s['duplicate_text_extra']}}}
\\newcommand{{\\SentLenTokMin}}{{{s['sentence_length_tokens']['min']}}}
\\newcommand{{\\SentLenTokMax}}{{{s['sentence_length_tokens']['max']}}}
\\newcommand{{\\SentLenTokMean}}{{{fnum(s['sentence_length_tokens']['mean'], 1)}}}
\\newcommand{{\\SentLenTokMedian}}{{{fnum(s['sentence_length_tokens']['median'], 1)}}}
\\newcommand{{\\SentLenTokStd}}{{{fnum(s['sentence_length_tokens']['std'], 1)}}}
\\newcommand{{\\SentLenCharMin}}{{{s['sentence_length_chars']['min']}}}
\\newcommand{{\\SentLenCharMax}}{{{s['sentence_length_chars']['max']}}}
\\newcommand{{\\SentLenCharMean}}{{{fnum(s['sentence_length_chars']['mean'], 1)}}}
"""

with open(os.path.join(BASE_DIR, "numbers.tex"), "w", encoding="utf-8") as f:
    f.write(macros)

# ---- Sample table: real rows for target word "জল" (jol), one row per sense ----
df = pd.read_excel(DATASET_PATH)
sub = (
    df[df["target_word"] == "জল"]
    .sort_values(["sense_id"])
    .groupby("sense_id")
    .head(2)
    .reset_index(drop=True)
)

rows_tex = []
for _, r in sub.iterrows():
    rows_tex.append(
        f"{r['word_id']} & \\bn{{{r['target_word']}}} & {r['sense_id']} & "
        f"\\bn{{{r['sense_gloss']}}} & \\bn{{{r['text']}}} \\\\"
    )

sample_table = (
    "% AUTO-GENERATED by generate_tables.py -- real rows from wsd_dataset.xlsx, target_word = \\bn{জল}\n"
    "\\begin{table}[htbp]\n"
    "\\caption{Sample rows from the released dataset for the target word \\bn{জল} (\\emph{jol}), "
    "illustrating three distinct senses of the same surface form, exactly as they appear in "
    "\\texttt{wsd\\_dataset.xlsx}.}\n"
    "\\label{tab:sample}\n"
    "\\centering\n"
    "\\footnotesize\n"
    "\\setlength{\\tabcolsep}{4pt}\n"
    "\\renewcommand{\\arraystretch}{1.3}\n"
    "\\begin{tabular}{@{}p{1.4cm}p{2.1cm}p{1.6cm}p{2.5cm}p{6.9cm}@{}}\n"
    "\\toprule\n"
    "\\texttt{word\\_id} & \\texttt{target\\_word} & \\texttt{sense\\_id} & "
    "\\texttt{sense\\_gloss} & \\texttt{text} \\\\\n"
    "\\midrule\n"
    + "\n".join(rows_tex) + "\n"
    "\\bottomrule\n"
    "\\end{tabular}\n"
    "\\end{table}\n"
)

with open(os.path.join(BASE_DIR, "sample_table.tex"), "w", encoding="utf-8") as f:
    f.write(sample_table)

print("OK -- wrote numbers.tex and sample_table.tex")
